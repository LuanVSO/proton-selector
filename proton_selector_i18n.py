CATALOGS = {
    language: dict(zip(MESSAGE_IDS, rows, strict=True))
    for language, rows in _CATALOG_ROWS.items()
}


def _normalize_locale_name(value: str) -> str:
    normalized = value.strip().split(".", 1)[0].split("@", 1)[0].replace("-", "_")
    if not normalized:
        return ""
    lowered = normalized.casefold()
    if lowered in {"c", "posix"}:
        return "en"
    parts = normalized.split("_", 1)
    language = parts[0].lower()
    region = parts[1].upper() if len(parts) > 1 else ""
    if language == "zh":
        if region in {"TW", "HK", "MO", "HANT"}:
            return "zh_TW"
        return "zh_CN"
    if language == "pt":
        return "pt_BR"
    return language


def select_language(env: Mapping[str, str] | None = None) -> str:
    environment = env if env is not None else os.environ
    candidates: list[str] = []
    override = environment.get("PROTON_SELECTOR_LANGUAGE", "")
    if override:
        candidates.append(override)
    language_list = environment.get("LANGUAGE", "")
    if language_list:
        candidates.extend(language_list.split(":"))
    candidates.extend(
        environment.get(name, "")
        for name in ("LC_ALL", "LC_MESSAGES", "LANG")
    )
    try:
        locale_name = locale.getlocale(locale.LC_MESSAGES)[0]
    except (TypeError, ValueError):
        locale_name = None
    if locale_name:
        candidates.append(locale_name)

    for candidate in candidates:
        language = _normalize_locale_name(candidate)
        if language in CATALOGS:
            return language
    return "en"


class Translator:
    def __init__(
        self,
        env: Mapping[str, str] | None = None,
        language: str | None = None,
    ) -> None:
        requested = _normalize_locale_name(language) if language else ""
        self.language = requested if requested in CATALOGS else select_language(env)
        self.catalog = CATALOGS[self.language]

    def set_language(self, language: str) -> None:
        normalized = _normalize_locale_name(language)
        if normalized not in CATALOGS:
            raise ValueError(f"Unsupported language: {language}")
        self.language = normalized
        self.catalog = CATALOGS[normalized]

    def use_system_language(
        self,
        env: Mapping[str, str] | None = None,
    ) -> None:
        self.set_language(select_language(env))

    def __call__(self, message_id: str, **values: object) -> str:
        try:
            message = self.catalog[message_id]
        except KeyError as error:
            raise KeyError(f"Unknown translation message: {message_id}") from error
        return message.format(**values)


translate = Translator()
